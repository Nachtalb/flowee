// bun scripts/compile.ts [--target <bun target>] [--outfile <path>]: the self-hosted runtime as ONE executable with
// the served material (scripts/bundle.ts) embedded, so a single file serves skills, docs, client and bundle.
// Targets: bun-linux-x64-musl (default; the Docker image), bun-linux-arm64-musl, bun-linux-x64, bun-darwin-arm64, …
export {};

declare const Bun: {
  Glob: new (p: string) => { scanSync(o: { cwd: string; onlyFiles?: boolean }): Iterable<string> };
  file(path: string): { bytes(): Promise<Uint8Array> };
  write(path: string, data: string): Promise<number>;
  spawnSync(cmd: string[], o?: { stdout?: "inherit"; stderr?: "inherit" }): { exitCode: number };
  CryptoHasher: new (alg: string) => { update(b: Uint8Array): void; digest(enc: "hex"): string };
};
declare const process: { argv: string[]; exit(code: number): never };

const arg = (k: string, d: string) => {
  const i = process.argv.indexOf(k);
  return i > 0 ? process.argv[i + 1] : d;
};
const target = arg("--target", "bun-linux-x64-musl");
const outfile = arg("--outfile", "dist/flowee");

const run = (cmd: string[]) => {
  if (Bun.spawnSync(cmd, { stdout: "inherit", stderr: "inherit" }).exitCode) process.exit(1);
};
run(["bun", "scripts/bundle.ts"]);
const files = [...new Bun.Glob("**/*").scanSync({ cwd: "served", onlyFiles: true })].sort();
const lines = ["// @ts-nocheck generated by scripts/compile.ts: the served material embedded in the executable (git-ignored).", "export const EMBEDDED: Record<string, [string, string]> = {};"];
for (const [i, f] of files.entries()) {
  const h = new Bun.CryptoHasher("sha256");
  h.update(await Bun.file(`served/${f}`).bytes());
  lines.splice(1 + i, 0, `import f${i} from "../../../served/${f}" with { type: "file" };`);
  lines.push(`EMBEDDED[${JSON.stringify(`/${f}`)}] = [f${i}, ${JSON.stringify(`"${h.digest("hex").slice(0, 32)}"`)}];`);
}
await Bun.write("src/runtime/bun/embedded.gen.ts", `${lines.join("\n")}\n`);
run(["bun", "build", "--compile", "--minify", "--sourcemap=none", `--target=${target}`, "src/runtime/bun/compiled.ts", "--outfile", outfile]);
console.log(`${outfile}: ${files.length} served files embedded, target ${target}`);

// Writes the setup wizard's chart (src/wizard/setup.json) as a mermaid diagram into docs/managed.md, between the
// markers; test/setup-chart.test.ts fails when the two drift.
import { readFileSync, writeFileSync } from "node:fs";
import { mermaid } from "../src/wizard/chart";

const path = new URL("../docs/managed.md", import.meta.url).pathname;
const doc = readFileSync(path, "utf8");
const re = /(<!-- setup chart: generated by scripts\/setup-chart\.ts -->\n)```mermaid\n[\s\S]*?```/;
if (!re.test(doc)) throw new Error("docs/managed.md has no generated setup chart block");
writeFileSync(path, doc.replace(re, (_, m: string) => `${m}\`\`\`mermaid\n${mermaid()}\`\`\``));
